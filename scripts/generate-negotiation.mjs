import fs from "node:fs";

// RFC 9110: the most specific matching media range supplies its quality.
// Both representations are UTF-8; other media parameters do not match.
// Generate portable nginx maps: no application server or nginx module needed.
export function negotiationConfig() {
  const lines = ["# Generated by scripts/generate-negotiation.mjs; do not edit by hand."];
  for (const [name, media] of [["md", "text/markdown"], ["html", "text/html"]]) {
    lines.push(`map $http_accept $hza_${name}_raw {`, '    default "0";', '    "" "1";');
    const charset = '\\s*;\\s*charset\\s*=\\s*(?:utf-8|\\x22utf-8\\x22)';
    for (const [index, range] of [media, "text/\\*", "\\*/\\*"].entries()) {
      // Parameter-specific ranges precede bare ones regardless of header order.
      for (const [specificity, parameter] of [charset, ""].entries()) {
        const capture = `hza_${name}_q${index}_${specificity}`;
        const prefix = `(?:^|,)\\s*${range}${parameter}`;
        // nginx quoted config strings need backslashes escaped once more.
        const quote = (value) => '"~*' + value.replaceAll("\\", "\\\\") + '"';
        lines.push(`    ${quote(`${prefix}\\s*;\\s*q\\s*=\\s*(?<${capture}>0(?:\\.[0-9]{0,3})?|1(?:\\.0{0,3})?)\\s*(?:,|$)`)} $${capture};`);
        lines.push(`    ${quote(`${prefix}\\s*(?:,|$)`)} "1";`);
      }
    }
    lines.push("}", `map $hza_${name}_raw $hza_${name}_quality {`, '    default "0000";', '    "1" "1000";', '    "~^1\\\\.0{0,3}$" "1000";', '    "0" "0000";', '    "0." "0000";');
    for (let digits = 1; digits <= 3; digits++) {
      lines.push(`    "~^0\\\\.(?<hza_${name}_digits${digits}>[0-9]{${digits}})$" "0\${hza_${name}_digits${digits}}${"0".repeat(3 - digits)}";`);
    }
    lines.push("}");
  }
  lines.push('map "$hza_md_quality:$hza_html_quality" $hza_representation {', '    default "html";', '    "0000:0000" "none";');
  // Compare four decimal digits from left to right. Equal quality prefers HTML.
  for (let position = 0; position < 4; position++) {
    const prefix = position ? `([0-9]{${position}})` : "";
    const backref = position ? "\\\\1" : "";
    const rest = position < 3 ? `[0-9]{${3 - position}}` : "";
    for (let digit = 1; digit <= 9; digit++) {
      // Brackets separate the backreference from the digit (\\10 means group 10).
      const lower = digit === 1 ? "[0]" : `[0-${digit - 1}]`;
      lines.push(`    "~^${prefix}${digit}${rest}:${backref}${lower}${rest}$" "md";`);
    }
  }
  lines.push("}", "map $hza_representation $hza_extension {", '    default "html";', '    md "md";', "}", "");
  return lines.join("\n");
}

if (process.argv[1]?.endsWith("generate-negotiation.mjs")) {
  fs.writeFileSync(new URL("../deploy/nginx/negotiation.conf", import.meta.url), negotiationConfig());
}
